	private void loadTarget(final Path target) throws IOException {
		LOGGER.debug("Loading analyze target: {}", target);
		if (Files.isDirectory(target)) {
			Files.walk(target)
				.filter(Files::isRegularFile)
				.filter(path -> path.getFileName().toString().endsWith(".class"))
				.forEach(path -> {
					try {
						parseClassBytes(Files.readAllBytes(path), path.toString());
					} catch (final IOException exception) {
						throw new IllegalStateException(exception);
					}
				});
			return;
		}
		final String fileName = target.getFileName().toString().toLowerCase();
		if (fileName.endsWith(".jar")) {
			loadJar(target);
			return;
		}
		if (fileName.endsWith(".class")) {
			parseClassBytes(Files.readAllBytes(target), target.toString());
		}
	}

	private void loadJar(final Path target) throws IOException {
		final JarInputStream jarInputStream = new JarInputStream(Files.newInputStream(target));
		try {
			JarEntry entry;
			while ((entry = jarInputStream.getNextJarEntry()) != null) {
				if (!entry.getName().endsWith(".class")) {
					continue;
				}
				parseClassBytes(readAllBytes(jarInputStream), target.toString() + "!/" + entry.getName());
			}
		} finally {
			jarInputStream.close();
		}
	}

