	private List<MethodCall> collectMethodCalls(final MethodNode methodNode) {
		final Map<AbstractInsnNode, Integer> instructionIndexes = new HashMap<AbstractInsnNode, Integer>();
		final List<LabelNode> mergeLabels = new ArrayList<LabelNode>();
		int index = 0;
		for (AbstractInsnNode instruction = methodNode.instructions.getFirst(); instruction != null; instruction = instruction.getNext()) {
			instructionIndexes.put(instruction, Integer.valueOf(index++));
			if (instruction instanceof JumpInsnNode) {
				mergeLabels.add(((JumpInsnNode) instruction).label);
			} else if (instruction instanceof TableSwitchInsnNode) {
				mergeLabels.add(((TableSwitchInsnNode) instruction).dflt);
				mergeLabels.addAll(((TableSwitchInsnNode) instruction).labels);
			} else if (instruction instanceof LookupSwitchInsnNode) {
				mergeLabels.add(((LookupSwitchInsnNode) instruction).dflt);
				mergeLabels.addAll(((LookupSwitchInsnNode) instruction).labels);
			}
		}
		final List<int[]> exceptionRanges = new ArrayList<int[]>();
		for (final TryCatchBlockNode tryCatchBlockNode : methodNode.tryCatchBlocks) {
			final Integer startIndex = instructionIndexes.get(tryCatchBlockNode.handler);
			if (startIndex == null) {
				continue;
			}
			int endIndex = methodNode.instructions.size();
			for (AbstractInsnNode cursor = tryCatchBlockNode.handler.getNext(); cursor != null; cursor = cursor.getNext()) {
				if (cursor instanceof LabelNode && mergeLabels.contains(cursor)) {
					endIndex = instructionIndexes.get(cursor).intValue();
					break;
				}
				final int opcode = cursor.getOpcode();
				if (opcode == Opcodes.GOTO || opcode == Opcodes.RETURN || opcode == Opcodes.IRETURN
					|| opcode == Opcodes.LRETURN || opcode == Opcodes.FRETURN || opcode == Opcodes.DRETURN
					|| opcode == Opcodes.ARETURN || opcode == Opcodes.ATHROW) {
					endIndex = instructionIndexes.get(cursor).intValue() + 1;
					break;
				}
			}
			exceptionRanges.add(new int[] {startIndex.intValue(), endIndex});
		}
		final List<MethodCall> calls = new ArrayList<MethodCall>();
		for (AbstractInsnNode instruction = methodNode.instructions.getFirst(); instruction != null; instruction = instruction.getNext()) {
			if (!(instruction instanceof MethodInsnNode)) {
				continue;
			}
			final MethodInsnNode methodInstruction = (MethodInsnNode) instruction;
			if ("<init>".equals(methodInstruction.name) || "<clinit>".equals(methodInstruction.name)) {
				continue;
			}
			final int currentIndex = instructionIndexes.get(instruction).intValue();
			final boolean exceptionHandler = isExceptionHandlerInstruction(currentIndex, exceptionRanges);
			calls.add(new MethodCall(methodInstruction.owner.replace('/', '.'), methodInstruction.name,
				methodInstruction.desc, exceptionHandler,
				methodInstruction.getOpcode() == Opcodes.INVOKEINTERFACE));
		}
		return calls;
	}

	private static boolean isExceptionHandlerInstruction(final int index, final List<int[]> exceptionRanges) {
		for (final int[] range : exceptionRanges) {
			if (index >= range[0] && index < range[1]) {
				return true;
			}
		}
		return false;
	}

	private static byte[] readAllBytes(final InputStream inputStream) throws IOException {
		final byte[] buffer = new byte[8192];
		int read;
		final java.io.ByteArrayOutputStream outputStream = new java.io.ByteArrayOutputStream();
		while ((read = inputStream.read(buffer)) >= 0) {
			outputStream.write(buffer, 0, read);
		}
		return outputStream.toByteArray();
	}

